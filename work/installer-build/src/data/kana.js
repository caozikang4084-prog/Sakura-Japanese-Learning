const row = (label, group, cells) => ({
  label,
  group,
  cells: cells.map((cell) => {
    if (!cell) return null;
    const [hira, kata, romaji] = cell;
    return hira ? { id: hira, hira, kata, romaji, group } : null;
  }),
});

